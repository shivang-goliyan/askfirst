"""Who fills the candidate list.

The engine never cared where candidates came from — rank_gaps has always taken them as an
argument. What the shortlist-recall measurement showed is that whoever fills the list sets the
ceiling for everything downstream, so the proposer is the part worth measuring.

Three of them here. Marginal is the one that failed. Pathology is a non-LLM attempt to do
better by reasoning through the differential instead of around it. Model is the real one, and it
needs a GPU."""

from collections import defaultdict


class MarginalProposer:
    """Rank every candidate by its own ablation influence. 223 scorer calls per field, and the
    one measured at 31.8% recall at k=20. Kept as the reference point."""

    def __init__(self, scorer, schema):
        self.scorer = scorer
        self.schema = schema

    def __call__(self, record, k=20):
        from .ablation import rank_gaps
        candidates = self.schema.missing_from(record)
        gaps = rank_gaps(record, self.scorer, self.schema, candidates=candidates)
        return [g.field for g in gaps[:k]]


class PathologyProposer:
    """Go through the differential rather than around it.

    Score the record, take the pathologies it currently considers plausible, and propose the
    evidences those pathologies most often present with that we have not already asked about.
    This is "if I suspect a PE, check a d-dimer" done statistically — still no medical knowledge,
    but conditioned on a hypothesis instead of a marginal count."""

    def __init__(self, scorer, model, top_pathologies=5):
        self.scorer = scorer
        self.model = model
        self.top_pathologies = top_pathologies
        self._by_pathology = self._index()

    def _index(self):
        """P(evidence present | pathology), off the counts the scorer already fitted.
        The denominator is how many patients had that pathology, not its prior probability."""
        out = defaultdict(dict)
        for (label, name), seen in self.model.field_seen.items():
            patients = self.model.counts.get(label, 0.0)
            if patients > 0:
                out[label][name] = seen / patients
        return out

    def __call__(self, record, k=20):
        """Propose what tells the leading hypotheses APART.

        Weighting by P(evidence | pathology) alone is a trap: it ranks evidence that every
        plausible pathology shares, which is exactly the evidence that settles nothing. What
        matters is disagreement, so score each candidate by how much its rate varies across the
        hypotheses still in play, weighted by how much we believe each one."""
        dist = self.scorer(record)
        leading = sorted(dist, key=dist.get, reverse=True)[: self.top_pathologies]
        mass = sum(dist[p] for p in leading) or 1.0
        belief = {p: dist[p] / mass for p in leading}

        rates = defaultdict(dict)
        for label in leading:
            for name, rate in self._by_pathology.get(label, {}).items():
                if name not in record:
                    rates[name][label] = rate

        spread = {}
        for name, by_label in rates.items():
            mean = sum(belief[p] * by_label.get(p, 0.0) for p in leading)
            spread[name] = sum(
                belief[p] * (by_label.get(p, 0.0) - mean) ** 2 for p in leading
            )

        return [n for n, _ in sorted(spread.items(), key=lambda kv: -kv[1])[:k]]


class ModelProposer:
    """The real one. Hands the record to an open model and asks which fields a clinician would
    want next. One generation per case. Needs a GPU, so it is a shell until credits land."""

    def __init__(self, client, schema, questions):
        self.client = client
        self.schema = schema
        self.questions = questions

    def __call__(self, record, k=20):
        raise NotImplementedError(
            "ModelProposer needs a served model. Point it at the vLLM endpoint once "
            "credits are in, then measure its recall at k=10 before trusting anything it says."
        )


def pipeline(record, scorer, schema, proposer, k=20):
    """Propose a shortlist, then ablate only that. The probabilities a user sees are computed
    here, not generated by whatever filled the list."""
    from .ablation import rank_gaps
    return rank_gaps(record, scorer, schema, candidates=proposer(record, k=k))
